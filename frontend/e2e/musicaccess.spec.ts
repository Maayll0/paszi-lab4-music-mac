import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { randomBytes } from 'node:crypto'
import { mkdir } from 'node:fs/promises'

const password = process.env.MUSICACCESS_TEST_PASSWORD!
async function screenshot(page: Page, name: string) {
  if (!process.env.CAPTURE_REPORT) return
  await mkdir('../report/screenshots', { recursive: true })
  await page.screenshot({ path: `../report/screenshots/${name}.png`, fullPage: true })
}
async function login(page: Page, name: string) {
  await page.goto('/login')
  await page.getByLabel('Логин', { exact: true }).fill(name)
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('link', { name, exact: true })).toBeVisible()
}

test('registration validation, duplicate, persisted session and account deletion', async ({ page }) => {
  const name = `listener_${randomBytes(5).toString('hex')}`
  await page.goto('/register')
  await page.getByLabel('Логин', { exact: true }).fill(name)
  await page.getByLabel('Пароль', { exact: true }).fill('weak')
  await page.getByLabel('Email', { exact: true }).fill('listener@example.com')
  await page.getByLabel('Я регистрирую музыкальный аккаунт').check()
  await page.getByRole('button', { name: 'Зарегистрироваться' }).click()
  await expect(page.getByRole('alert')).toContainText('Пароль:')
  await screenshot(page, '01-weak-password')
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await screenshot(page, '02-registration')
  await page.getByRole('button', { name: 'Зарегистрироваться' }).click()
  await expect(page.getByRole('status')).toContainText('Регистрация успешна')
  await screenshot(page, '03-registration-success')
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Зарегистрироваться' }).click()
  await expect(page.getByRole('alert')).toContainText('логин уже занят')
  await screenshot(page, '04-duplicate-login')
  await login(page, name)
  await page.reload()
  await expect(page.getByRole('link', { name, exact: true })).toBeVisible()
  await screenshot(page, '05-authenticated-catalogue')
  await page.getByRole('button', { name: 'Выйти' }).click()
  await expect(page.getByRole('link', { name: 'Войти', exact: true })).toBeVisible()
  await login(page, name)
  await page.getByRole('link', { name, exact: true }).click()
  await page.getByLabel('Подтвердите пароль').fill(password)
  await page.getByLabel('Я подтверждаю удаление аккаунта').check()
  await page.getByRole('button', { name: 'Удалить аккаунт' }).click()
  await expect(page).toHaveURL(/\/login$/)
  const me = await page.request.get('/api/me')
  expect(me.status()).toBe(401)
})

test('debounced suggestions, URL filters, direct links and browser history', async ({ page }) => {
  await page.goto('/music')
  await page.getByLabel('Название или исполнитель', { exact: true }).fill('Night')
  await expect(page).toHaveURL(/q=Night/)
  await expect(page.getByRole('list', { name: 'Поисковые подсказки' }).getByRole('link')).toContainText('Night Drive')
  await screenshot(page, '06-search-suggestions')
  await page.getByRole('list', { name: 'Поисковые подсказки' }).getByRole('link').click()
  await expect(page.getByRole('heading', { name: 'Night Drive' })).toBeVisible()
  await page.goto('/music?title=Night&artist=Electronic')
  await expect(page.locator('.track-card')).toHaveCount(1)
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue('Night')
  await screenshot(page, '07-url-filters')
  await page.getByRole('button', { name: 'Сбросить' }).click()
  await expect(page).toHaveURL(/\/music$/)
  await expect(page.locator('.track-card')).toHaveCount(3)
  await page.goBack()
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue('Night')
  await expect(page.locator('.track-card')).toHaveCount(1)
  await page.waitForTimeout(600)
  await expect(page).toHaveURL(/title=Night&artist=Electronic/)
  await page.goForward()
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue('')
  await page.getByLabel('Название', { exact: true }).fill('Не найдено & +')
  await expect(page.getByRole('status')).toContainText('Композиции не найдены')
  await page.reload()
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue('Не найдено & +')
})

test('public playback, seeking, logout revocation and actual 403 redirect', async ({ page }) => {
  await login(page, 'demo_public')
  await page.goto('/music/1')
  await page.getByRole('button', { name: 'Слушать' }).click()
  const audio = page.locator('audio')
  await expect(audio).toBeVisible()
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => node.duration)).toBe(24)
  await audio.evaluate(async (node: HTMLAudioElement) => { await node.play(); node.currentTime = 12; node.volume = 0.3 })
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => node.currentTime)).toBeGreaterThan(12)
  await screenshot(page, '08-public-player')
  await page.goto('/music/2')
  const denied = page.waitForResponse(response => response.url().endsWith('/api/tracks/2/stream'))
  await page.getByRole('button', { name: 'Слушать' }).click()
  expect((await denied).status()).toBe(403)
  await expect(page).toHaveURL(/\/access-denied$/)
  await screenshot(page, '09-access-denied')
  await page.goto('/music/1')
  await page.getByRole('button', { name: 'Слушать' }).click()
  await expect(page.locator('audio')).toBeVisible()
  await page.getByRole('button', { name: 'Выйти' }).click()
  await expect(page.locator('audio')).toHaveCount(0)
  expect((await page.request.get('/api/tracks/1/stream')).status()).toBe(401)
})

